/** ที่อยู่ของไฟล์ในโฟลเดอร์ public
 *
 *  เขียน `/assets/x.png` ตรงๆ จะได้เส้นทางที่อิง *รากของโดเมน* ซึ่งใช้ได้เฉพาะตอน
 *  เกมอยู่ที่รากเท่านั้น พอเอาไปวางใต้โฟลเดอร์ย่อยของโฮสต์อื่นจะ 404 ทั้งหมด
 *  ตัวนี้แปลงให้อิงตำแหน่งของหน้าเว็บเองเสมอ (`base` ใน vite.config.ts = "./")
 */
export const asset = (path: string): string =>
  import.meta.env.BASE_URL.replace(/\/$/, "") + "/" + path.replace(/^\//, "");
